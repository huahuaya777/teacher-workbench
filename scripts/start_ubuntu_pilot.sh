#!/usr/bin/env bash
# Start only the separate, empty EasyTier HTTPS pilot after config validation.
set -euo pipefail
umask 077

if [[ "$(hostname)" != teacher-workbench || "$(id -un)" != huahua ||
      "$HOME" != /home/huahua || "$#" != 0 ]]; then
  echo PILOT_START_WRONG_HOST_OR_USER
  exit 1
fi

target="$HOME/teacher-workbench-pilot"
backup="$HOME/teacher-workbench-staging-backups/backup-staging-errors-CLQ37z6Q"
[[ ! -L "$target" && -d "$target" && "$(stat -c %a "$target")" == 700 ]]
[[ "$(cat "$target/STATE")" == PILOT_CONFIG_PREPARED ]]
[[ ! -L "$backup" && -d "$backup" ]]
(cd "$backup" && sha256sum -c SHA256SUMS >/dev/null)
(cd "$target" && sha256sum -c SHA256SUMS >/dev/null)
cd "$target"
python3 check_pilot_env.py --env-file .env.pilot

# These values are generated by the checked local program; do not eval the env file.
readarray -t values < <(python3 - <<'PY'
from pathlib import Path
values = dict(line.split('=', 1) for line in Path('.env.pilot').read_text().splitlines() if '=' in line)
print(values['PILOT_KEYRING_DIR'])
print(values['PILOT_APP_IMAGE'])
PY
)
keyring="${values[0]}"
app_image="${values[1]}"
[[ ! -L "$keyring" && -d "$keyring" && "$(stat -c %a "$keyring")" == 700 ]]
[[ ! -L "$keyring/v1.key" && -f "$keyring/v1.key" &&
   "$(stat -c %a "$keyring/v1.key")" == 600 ]]
[[ "$(cat "$backup/APP_IMAGE_ID")" == "$app_image" ]]

sudo -v
[[ "$(timeout 10s sudo -n docker inspect -f '{{.Image}}' teacher-workbench-staging-web-1)" == "$app_image" ]]
timeout 20s sudo -n docker compose --env-file .env.pilot -f compose.pilot.yaml config --quiet
if ss -H -ltn | awk '{print $4}' | grep -Eq '(^|:)18443$'; then
  echo PILOT_START_PORT_IN_USE
  exit 1
fi
ip -4 -o addr show | awk '{print $4}' | grep -Fxq '10.0.30.5/24'
if timeout 10s sudo -n docker container ls -a --format '{{.Names}}' |
    grep -Eq '^teacher-workbench-pilot-'; then
  echo PILOT_START_EXISTING_CONTAINER
  exit 1
fi
if timeout 10s sudo -n docker volume ls --format '{{.Name}}' |
    grep -Eq '^teacher-workbench-pilot_'; then
  echo PILOT_START_EXISTING_VOLUME
  exit 1
fi

status="$(curl --silent --show-error --max-time 8 --output /dev/null --write-out '%{http_code}' http://127.0.0.1:18002/login/)"
[[ "$status" == 200 ]]
echo PILOT_START_PREFLIGHT_OK

printf 'PILOT_STARTING\n' > STATE
compose=(sudo -n docker compose --env-file .env.pilot -f compose.pilot.yaml)
"${compose[@]}" up -d --no-build db redis
for attempt in $(seq 1 30); do
  db_health="$(timeout 8s sudo -n docker inspect -f '{{.State.Health.Status}}' teacher-workbench-pilot-db-1)"
  redis_health="$(timeout 8s sudo -n docker inspect -f '{{.State.Health.Status}}' teacher-workbench-pilot-redis-1)"
  if [[ "$db_health" == healthy && "$redis_health" == healthy ]]; then
    break
  fi
  sleep 2
done
[[ "$db_health" == healthy && "$redis_health" == healthy ]]
echo PILOT_DATABASE_AND_REDIS_HEALTHY
"${compose[@]}" run --rm --no-deps web sh -c \
  'python scripts/check_pilot_env.py --process-env && python manage.py migrate --noinput'
"${compose[@]}" up -d --no-build web gateway

for attempt in $(seq 1 30); do
  if timeout 8s sudo -n docker exec teacher-workbench-pilot-gateway-1 \
      test -s /data/caddy/pki/authorities/local/root.crt >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
timeout 10s sudo -n docker exec teacher-workbench-pilot-gateway-1 \
  cat /data/caddy/pki/authorities/local/root.crt > pilot-root-ca.crt
[[ -s pilot-root-ca.crt ]]

login_status=""
static_status=""
for attempt in $(seq 1 30); do
  login_status="$(curl --noproxy '*' --silent --max-time 8 \
    --cacert pilot-root-ca.crt --output /dev/null --write-out '%{http_code}' \
    https://10.0.30.5:18443/login/ 2>/dev/null || true)"
  static_status="$(curl --noproxy '*' --silent --max-time 8 \
    --cacert pilot-root-ca.crt --output /dev/null --write-out '%{http_code}' \
    https://10.0.30.5:18443/static/workbench/site.css 2>/dev/null || true)"
  if [[ "$login_status" == 200 && "$static_status" == 200 ]]; then
    break
  fi
  sleep 2
done
[[ "$login_status" == 200 && "$static_status" == 200 ]] || {
  echo PILOT_HTTPS_SMOKE_FAILED
  exit 1
}
[[ "$(curl --silent --show-error --max-time 8 --output /dev/null --write-out '%{http_code}' http://127.0.0.1:18002/login/)" == 200 ]]

printf 'PILOT_STARTED_AI_OFF\n' > STATE
echo PILOT_HTTPS_LOGIN_AND_STATIC_TRUSTED_LOCALLY_200
echo PILOT_STAGING_LOGIN_STILL_HTTP_200
openssl x509 -in pilot-root-ca.crt -noout -fingerprint -sha256
echo "PILOT_ROOT_CA_PATH=$target/pilot-root-ca.crt"
echo PILOT_STARTED_SEPARATE_AI_OFF
